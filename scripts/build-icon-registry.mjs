import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';

const root=fileURLToPath(new URL('..',import.meta.url));
const assets=path.join(root,'design-system/assets/icons/native-quiet');
const output=path.join(root,'design-system/icons.js');

export async function iconRegistrySource(){
  const manifest=JSON.parse(await readFile(path.join(assets,'manifest.json'),'utf8'));
  const definitions={};
  for(const entry of manifest.entries){
    const raw=await readFile(path.resolve(assets,entry.asset),'utf8');
    const svg=raw.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/);
    if(!svg||/<script\b|\bon\w+=|<foreignObject\b|(?:href|src)\s*=\s*["']https?:/i.test(raw))throw Error(`Invalid icon: ${entry.id}`);
    const attributes=Object.fromEntries([...svg[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map(match=>[match[1],match[2]]));
    definitions[entry.id]={viewBox:attributes.viewBox||'0 0 24 24',body:svg[2].trim(),fill:attributes.fill||'none',stroke:entry.kind==='brand'?'none':attributes.stroke||'none',strokeWidth:attributes['stroke-width']||'0',kind:entry.kind};
  }
  const aliases={meeting:'notebook-tabs',sources:'folder-open',people:'users',close:'x',arrow:'arrow-right',ask:'messages-square',doc:'file-text',calendar:'calendar-days',filter:'list-filter','more-horizontal':'ellipsis'};
  const generated=`// Generated by scripts/build-icon-registry.mjs from the selected Native Quiet assets.\n(function (root) {\n  const definitions = ${JSON.stringify(definitions,null,2)};\n  for (const definition of Object.values(definitions)) Object.freeze(definition);\n  Object.freeze(definitions);\n  const aliases = ${JSON.stringify(aliases,null,2)};\n  const resolve = name => Object.hasOwn(definitions, aliases[name] || name) ? aliases[name] || name : 'file-text';\n  function icon(name) {\n    const id = resolve(name), shape = definitions[id];\n    return '<svg class="lucide lucide-' + id + ' nero-icon' + (shape.kind === 'brand' ? ' nero-icon-brand' : '') + '" data-nero-icon="' + id + '" viewBox="' + shape.viewBox + '" width="18" height="18" fill="' + shape.fill + '" stroke="' + shape.stroke + '" stroke-width="' + shape.strokeWidth + '" stroke-linecap="round" stroke-linejoin="round" style="fill:' + shape.fill + ';stroke:' + shape.stroke + ';stroke-width:' + shape.strokeWidth + '" aria-hidden="true" focusable="false">' + shape.body + '</svg>';\n  }\n  icon.definition = name => definitions[resolve(name)];\n  icon.names = Object.freeze(Object.keys(definitions));\n  root.NeroIcons = icon;\n})(typeof globalThis === 'object' ? globalThis : this);\n`;
  return generated;
}

export async function buildIconRegistry({check=false}={}){
  const generated=await iconRegistrySource();
  const current=await readFile(output,'utf8').catch(error=>{if(error.code==='ENOENT')return null;throw error;});
  if(check){
    if(current!==generated)throw Error('Icon registry differs from its SVG sources. Run node scripts/build-icon-registry.mjs.');
  }else if(current!==generated)await writeFile(output,generated);
}

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
  const args=process.argv.slice(2);
  if(args.length>1||args.length===1&&args[0]!=='--check')throw Error('Usage: node scripts/build-icon-registry.mjs [--check]');
  await buildIconRegistry({check:args[0]==='--check'});
  console.log(args[0]==='--check'?'Icon SVG sources and registry match.':'Icon registry generated from SVG sources.');
}
