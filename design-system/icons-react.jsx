import * as React from 'react';
import './icons.js';

// The plain DOM renderer and React controls share the same canonical geometry.
export const NeroIcon=React.forwardRef(function NeroIcon({name,size=24,color='currentColor',strokeWidth,stroke,fill,absoluteStrokeWidth=false,className='',style,children,...props},ref){
  const definition=globalThis.NeroIcons.definition(name);
  const viewHeight=Number(definition.viewBox.split(/\s+/)[3]);
  const width=strokeWidth===undefined?Number(definition.strokeWidth):Number(strokeWidth)*viewHeight/24;
  const displayedWidth=absoluteStrokeWidth?width*24/Number(size):width;
  const effectiveFill=fill??definition.fill, effectiveStroke=stroke??definition.stroke;
  const hidden=props['aria-hidden']??(props['aria-label']||props['aria-labelledby']?undefined:true);
  return <svg ref={ref} xmlns="http://www.w3.org/2000/svg" className={`lucide lucide-${name} nero-icon ${definition.kind==='brand'?'nero-icon-brand ':''}${className}`} data-nero-icon={name} viewBox={definition.viewBox} width={size} height={size} color={color} fill={effectiveFill} stroke={effectiveStroke} strokeWidth={displayedWidth} style={{fill:effectiveFill,stroke:effectiveStroke,strokeWidth:displayedWidth,...style}} strokeLinecap="round" strokeLinejoin="round" aria-hidden={hidden} focusable="false" {...props}><g dangerouslySetInnerHTML={{__html:definition.body}}/>{children}</svg>;
});
function createIcon(name,displayName){
  const Icon=React.forwardRef((props,ref)=><NeroIcon name={name} ref={ref} {...props}/>);
  Icon.displayName=displayName;
  return Icon;
}
