import assert from 'node:assert/strict';
import test from 'node:test';
import { build } from 'esbuild';
import { Window } from 'happy-dom';
import { fileURLToPath } from 'node:url';

test('calendar picker renders one explicit selection and keeps linked metadata separate from manual fields', async t => {
  const app = fileURLToPath(new URL('../', import.meta.url));
  const bundle = await build({ entryPoints: [app + 'src/calendar-meeting-picker.jsx'], nodePaths: [app + 'node_modules'], bundle: true, write: false, format: 'iife', globalName: 'CalendarMeetingUI', loader: { '.css': 'empty' }, define: { 'process.env.NODE_ENV': '"production"' } });
  const window = new Window({ url: 'http://nero.test', settings: { enableJavaScriptEvaluation: true, suppressInsecureJavaScriptEnvironmentWarning: true } });
  t.after(() => window.happyDOM.abort());
  window.document.body.innerHTML = '<button id="trigger">일정에서 준비</button><div id="reference"></div>';
  window.eval(bundle.outputFiles[0].text);
  const event = { key: 'one', title: 'Provider title', startAt: 1_000_000, endAt: 2_000_000, calendarName: 'Synthetic', joinUrls: ['https://example.test/join'] };
  const calls = [], queries = [];
  const picker = window.CalendarMeetingUI.mountCalendarMeetingPicker({ container: window.document.body, bridge: { readCalendarMeetingOccurrences: async query => { queries.push(query); return { calendar: { connected: true, selectedCalendars: ['one'] }, occurrences: [event], ...query, scopeRevision: 2 }; }, createMeetingFromCalendar: async key => { calls.push(key); return { id: 'one' }; } }, onPrepared() {} });
  t.after(() => picker.dispose());
  const wait = async predicate => { for (let i = 0; i < 100; i++) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 5)); } assert.fail('Expected calendar picker state'); };
  const button = text => [...window.document.querySelectorAll('button')].find(node => node.textContent === text);
  picker.open(window.document.getElementById('trigger'));
  await wait(() => window.document.querySelector('input[type="radio"]'));
  assert.equal(button('일정 연결').disabled, true);
  assert.equal(window.document.querySelectorAll('input[type="radio"]').length, 1);
  assert.match(window.document.body.textContent, /Provider title/);
  assert.deepEqual(calls, []);
  const initialDay = queries[0].day;
  const tomorrow = new Date(`${initialDay}T12:00:00`);
  tomorrow.setDate(tomorrow.getDate() + 1);
  const tomorrowKey = `${tomorrow.getFullYear()}-${String(tomorrow.getMonth() + 1).padStart(2, '0')}-${String(tomorrow.getDate()).padStart(2, '0')}`;
  const tomorrowLabel = `${tomorrow.getFullYear()}년 ${tomorrow.getMonth() + 1}월 ${tomorrow.getDate()}일 ${['일요일', '월요일', '화요일', '수요일', '목요일', '금요일', '토요일'][tomorrow.getDay()]}`;
  window.document.querySelector('.calendar-meeting-date .nero-date-trigger').click();
  await wait(() => window.document.querySelector(`button[aria-label="${tomorrowLabel}"]`));
  const tomorrowButton = window.document.querySelector(`button[aria-label="${tomorrowLabel}"]`);
  tomorrowButton.dispatchEvent(new window.PointerEvent('pointerdown', { bubbles: true, pointerType: 'mouse', button: 0 }));
  tomorrowButton.dispatchEvent(new window.MouseEvent('mousedown', { bubbles: true, button: 0 }));
  tomorrowButton.focus();
  tomorrowButton.dispatchEvent(new window.PointerEvent('pointerup', { bubbles: true, pointerType: 'mouse', button: 0 }));
  tomorrowButton.dispatchEvent(new window.MouseEvent('mouseup', { bubbles: true, button: 0 }));
  tomorrowButton.click();
  await wait(() => queries.length === 2 && queries[1].day === tomorrowKey && window.document.querySelector('input[type="radio"]'));
  assert.match(window.document.querySelector('.calendar-meeting-date .nero-date-trigger').getAttribute('aria-label'), new RegExp(`${tomorrow.getDate()}일`));
  window.document.querySelector('[aria-label="이전 날짜"]').click();
  await wait(() => queries.length === 3 && window.document.querySelector('input[type="radio"]'));
  assert.equal(queries[2].day, initialDay);
  window.document.querySelector('.calendar-meeting-date .nero-date-trigger').click();
  await wait(() => window.document.querySelector('[aria-label="다음 달"]'));
  const caption = window.document.querySelector('.rdp-month_caption').textContent;
  window.document.querySelector('[aria-label="다음 달"]').click();
  await wait(() => window.document.querySelector('.rdp-month_caption').textContent !== caption);
  const day = [...window.document.querySelectorAll('.rdp-day_button')].find(node => node.textContent === '15');
  assert.ok(day); day.click();
  await new Promise(resolve => setTimeout(resolve, 0));
  await wait(() => queries.length === 4 && window.document.querySelector('input[type="radio"]'));
  assert.notEqual(queries[2].day, queries[3].day);
  assert.deepEqual(calls, []);
  window.document.querySelector('input[type="radio"]').click();
  await wait(() => !button('일정 연결').disabled);
  assert.match(window.document.body.textContent, /https:\/\/example.test\/join/);
  button('일정 연결').click(); await wait(() => calls.length === 1 && !picker.isOpen());
  assert.deepEqual(calls, ['one']);
  await wait(() => window.document.activeElement.id === 'trigger');
  const reference = window.CalendarMeetingUI.mountCalendarMeetingReference({ container: window.document.getElementById('reference') });
  t.after(() => reference.dispose());
  reference.render({ title: 'Manual title', notes: 'Manual notes', calendarReference: { ...event, occurrenceKey: event.key } });
  await wait(() => window.document.getElementById('reference').textContent.includes('Provider title'));
  assert.equal(window.document.getElementById('reference').textContent.includes('Manual notes'), false);
  reference.render({ title: 'Plain meeting' });
  assert.equal(window.document.getElementById('reference').hidden, true);
});
